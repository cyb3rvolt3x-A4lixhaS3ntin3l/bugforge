def _resolve_cname(subdomain: str) -> str:
    """
    Resolve the CNAME for a subdomain. socket doesn't expose CNAME directly,
    so we use gethostbyaddr-free approach: query with a manual resolver that
    inspects the getaddrinfo result.

    When a CNAME exists, socket.gethostbyname_ex returns the canonical name
    in the second element of its tuple.
    """
    try:
        # gethostbyname_ex returns (hostname, aliaslist, ipaddrlist).
        # For a CNAME, the primary 'hostname' is the canonical (resolved)
        # name, and 'aliaslist' contains the queried name.
        hostname, aliases, ips = socket.gethostbyname_ex(subdomain)
        if hostname and hostname.lower() != subdomain.lower():
            return hostname
        # Some resolvers put the CNAME target in the alias list.
        for alias in aliases:
            if alias.lower() != subdomain.lower():
                return alias
    except socket.gaierror:
        # NXDOMAIN — try a raw DNS CNAME query as a fallback (no external dep).
        return _manual_cname_query(subdomain)
    except Exception as e:
        log.debug(f"subdomain_takeover: CNAME resolution error for {subdomain}: {e}")
    return ""


def _manual_cname_query(subdomain: str) -> str:
    """
    Last-resort raw DNS query for CNAME records over UDP/53 using the public
    resolver 8.8.8.8. Pure stdlib — no dnspython.

    Returns the CNAME target as a string, or "" on failure.
    """
    try:
        # Build a minimal DNS query for type CNAME (5), class IN (1).
        transaction_id = b"\x12\x34"
        flags = b"\x01\x00"  # standard query, recursion desired
        qdcount = b"\x00\x01"
        ancount = b"\x00\x00"
        nscount = b"\x00\x00"
        arcount = b"\x00\x00"
        header = transaction_id + flags + qdcount + ancount + nscount + arcount

        # Encode the name as length-prefixed labels.
        question = b""
        for label in subdomain.split("."):
            encoded = label.encode("ascii")
            question += bytes([len(encoded)]) + encoded
        question += b"\x00"
        question += b"\x00\x05"  # type CNAME
        question += b"\x00\x01"  # class IN

        packet = header + question

        sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        sock.settimeout(4)
        sock.sendto(packet, ("8.8.8.8", 53))
        data, _ = sock.recvfrom(1024)
        sock.close()

        # Parse the response. Skip header (12 bytes) + question section.
        # Then parse answer records looking for type CNAME (5).
        offset = 12
        # Skip question section (name + type(2) + class(2)).
        offset = _skip_name(data, offset)
        offset += 4  # type + class

        ancount = int.from_bytes(data[6:8], "big")
        for _ in range(ancount):
            offset = _skip_name(data, offset)
            rtype = int.from_bytes(data[offset:offset + 2], "big")
            offset += 2
            rclass = int.from_bytes(data[offset:offset + 2], "big")
            offset += 2
            ttl = int.from_bytes(data[offset:offset + 4], "big")
            offset += 4
            rdlength = int.from_bytes(data[offset:offset + 2], "big")
            offset += 2
            rdata = data[offset:offset + rdlength]
            offset += rdlength
            if rtype == 5:  # CNAME
                # Decode the domain name in rdata (with compression).
                cname = _decode_name(data, offset - rdlength)
                return cname.rstrip(".")
        return ""
    except Exception as e:
        log.debug(f"subdomain_takeover: manual CNAME query failed for {subdomain}: {e}")
        return ""


def _skip_name(data: bytes, offset: int) -> int:
    """Skip a DNS name (label sequence) in `data` starting at `offset`."""
    while offset < len(data):
        length = data[offset]
        if length == 0:
            return offset + 1
        if (length & 0xC0) == 0xC0:  # compression pointer
            return offset + 2
        offset += length + 1
    return offset


def _decode_name(data: bytes, offset: int) -> str:
    """Decode a DNS name (handling compression pointers) starting at offset."""
    labels = []
    jumped = False
    original_offset = offset
    while offset < len(data):
        length = data[offset]
        if length == 0:
            break
        if (length & 0xC0) == 0xC0:
            pointer = ((length & 0x3F) << 8) | data[offset + 1]
            if not jumped:
                original_offset = offset + 2
            offset = pointer
            jumped = True
            continue
        offset += 1
        labels.append(data[offset:offset + length].decode("ascii", errors="replace"))
        offset += length
    return ".".join(labels)


def _fetch(url: str, timeout: int = 10) -> dict:
    """Fetch a URL; return {'status', 'body'} (both empty/zero on failure)."""
    req = urllib.request.Request(url, headers={
        "User-Agent": "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 "
                      "Chrome/120.0 Safari/537.36",
    })
    ctx = ssl.create_default_context()
    ctx.check_hostname = False
    ctx.verify_mode = ssl.CERT_NONE
    try:
        with urllib.request.urlopen(req, timeout=timeout, context=ctx) as resp:
            return {
                "status": resp.status,
                "body": resp.read().decode("utf-8", errors="replace")[:4096],
            }
    except urllib.error.HTTPError as e:
        body = ""
        try:
            body = e.read().decode("utf-8", errors="replace")[:4096]
        except Exception:
            pass
        return {"status": e.code, "body": body}
    except Exception:
        return {"status": 0, "body": ""}
