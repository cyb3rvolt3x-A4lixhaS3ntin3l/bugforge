def check_takeover(subdomain: str) -> List[dict]:
    """
    Check a single subdomain for takeover potential.

    Steps:
      1. Resolve CNAME chain via socket.gethostbyname_ex + a CNAME lookup.
      2. If NXDOMAIN (dead DNS) → vulnerable.
      3. If CNAME points at a known service, fetch the resolved host and
         match the fingerprint.

    Returns a list of finding dicts.
    """
    findings: List[dict] = []
    subdomain = subdomain.strip().lower().rstrip(".")

    # 1. Resolve A record / check for NXDOMAIN.
    try:
        socket.gethostbyname(subdomain)
    except socket.gaierror as e:
        # NXDOMAIN (dead DNS). A dangling record pointing at a dead name
        # can often be claimed by registering that name.
        if "not found" in str(e).lower() or "name or service not known" in str(e).lower() \
                or "no data" in str(e).lower():
            # But first confirm there is a CNAME pointing somewhere — a dead
            # subdomain with no CNAME at all is just dead, not takeovable.
            cname = _resolve_cname(subdomain)
            if cname:
                findings.append({
                    "type": "subdomain_takeover",
                    "severity": "high",
                    "description": (
                        f"Subdomain '{subdomain}' has a CNAME to '{cname}' "
                        "but does not resolve (NXDOMAIN) — potential takeover "
                        "if '{cname}' can be registered"
                    ),
                    "url": subdomain,
                    "source": "subdomain_takeover",
                    "subdomain": subdomain,
                    "cname": cname,
                    "indicator": "nxdomain_with_cname",
                })
            else:
                findings.append({
                    "type": "subdomain_takeover",
                    "severity": "info",
                    "description": (
                        f"Subdomain '{subdomain}' does not resolve (NXDOMAIN) "
                        "and has no CNAME — dead subdomain, not takeovable"
                    ),
                    "url": subdomain,
                    "source": "subdomain_takeover",
                    "subdomain": subdomain,
                    "indicator": "nxdomain_no_cname",
                })
            return findings

    # 2. Resolve the CNAME chain.
    cname = _resolve_cname(subdomain)
    if not cname:
        # No CNAME and the host resolves — not a takeover candidate.
        return findings

    cname_low = cname.lower().rstrip(".")

    # 3. Match against known services.
    for svc in SERVICE_FINGERPRINTS:
        if not any(suf.lower().rstrip(".") in cname_low for suf in svc["cname_match"]):
            continue

        # Fetch the resolved host to confirm the fingerprint.
        target_url = f"http://{subdomain}/"
        result = _fetch(target_url)
        body = result["body"]
        status = result["status"]

        confirmed = False
        for sig in svc["body_signatures"]:
            if sig.lower() in body.lower():
                confirmed = True
                break
        # Also accept the documented HTTP status as a softer indicator.
        if status in svc.get("http_status", []) and not confirmed:
            confirmed = True  # weak confirmation; lower severity below.

        if confirmed:
            severity = svc["severity"] if body else "medium"
            findings.append({
                "type": "subdomain_takeover",
                "severity": severity,
                "description": (
                    f"Subdomain '{subdomain}' CNAME → '{cname}' points to "
                    f"decommissioned {svc['service']} service — takeover "
                    "likely if you can claim the resource"
                ),
                "url": target_url,
                "source": "subdomain_takeover",
                "subdomain": subdomain,
                "cname": cname,
                "service": svc["service"],
                "indicator": "fingerprint_match",
                "status": status,
            })
        else:
            findings.append({
                "type": "subdomain_takeover",
                "severity": "low",
                "description": (
                    f"Subdomain '{subdomain}' CNAME → '{cname}' matches "
                    f"{svc['service']} but the fingerprint did not confirm — "
                    "verify manually"
                ),
                "url": target_url,
                "source": "subdomain_takeover",
                "subdomain": subdomain,
                "cname": cname,
                "service": svc["service"],
                "indicator": "cname_match_no_fingerprint",
                "status": status,
            })
        return findings

    # CNAME points somewhere unknown — note for triage.
    findings.append({
        "type": "subdomain_takeover",
        "severity": "info",
        "description": (
            f"Subdomain '{subdomain}' has CNAME → '{cname}' to an unknown "
            "service — investigate manually for takeover potential"
        ),
        "url": f"http://{subdomain}/",
        "source": "subdomain_takeover",
        "subdomain": subdomain,
        "cname": cname,
        "indicator": "unknown_cname",
    })
    return findings


